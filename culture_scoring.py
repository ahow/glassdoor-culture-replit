def score_review_with_dictionary(review_text: str) -> Dict:
    """
    Score a review using weighted dictionary-based approach.
    Returns scores for all Hofstede and MIT Big 9 dimensions.

    Hofstede:  score = (weighted_pole_B - weighted_pole_A)
                       / (weighted_pole_A + weighted_pole_B)   in [-1, +1]
               Returns None when no evidence found (topic not mentioned).

    MIT Big 9: score = min(10, weighted_match_sum * 2)          in [0, 10]
               0 when no keywords matched.
    """
    if not review_text or not isinstance(review_text, str):
        return None

    text_lower = review_text.lower()
    scores = {
        "hofstede": {},
        "mit_big_9": {},
        "schroders": {},
        "scoring_method": "dictionary"
    }

    # ── Hofstede ────────────────────────────────────────────────────────────
    for dimension, poles in HOFSTEDE_DIMENSIONS.items():
        pole_keys = list(poles.keys())
        pole_a_key = pole_keys[0]
        pole_b_key = pole_keys[1]

        pole_a_score = sum(w for phrase, w in poles[pole_a_key].items() if phrase in text_lower)
        pole_b_score = sum(w for phrase, w in poles[pole_b_key].items() if phrase in text_lower)
        total_evidence = pole_a_score + pole_b_score

        if total_evidence == 0:
            score = None
        else:
            score = round((pole_b_score - pole_a_score) / total_evidence, 4)

        scores["hofstede"][dimension] = {
            "score": score,
            "confidence": "medium" if score is not None else "low",
            "evidence_count": round(total_evidence, 4)
        }

    # ── MIT Big 9 ────────────────────────────────────────────────────────────
    for dimension, keywords in MIT_BIG_9_KEYWORDS.items():
        weighted_sum = sum(w for kw, w in keywords.items() if kw in text_lower)
        score = min(10.0, weighted_sum * 2) if weighted_sum > 0 else 0.0

        scores["mit_big_9"][dimension] = {
            "score": round(score, 4),
            "confidence": "medium" if score > 0 else "low",
            "evidence_count": round(weighted_sum, 4)
        }

    # ── Schroders (18 bipolar dimensions) ────────────────────────────────────
    # Positive-direction words push score toward +1, negative-direction toward -1.
    #   score = (pos_sum - neg_sum) / (pos_sum + neg_sum)   in [-1, +1]
    # Returns None when the dimension is not mentioned at all.
    for dimension in SCHRODERS_DIMENSIONS:
        kw = SCHRODERS_KEYWORDS[dimension]
        pos_sum = sum(w for phrase, w in kw["positive"].items() if phrase in text_lower)
        neg_sum = sum(w for phrase, w in kw["negative"].items() if phrase in text_lower)
        total_evidence = pos_sum + neg_sum

        if total_evidence == 0:
            s_score = None
        else:
            s_score = round((pos_sum - neg_sum) / total_evidence, 4)

        scores["schroders"][dimension] = {
            "score": s_score,
            "confidence": "medium" if s_score is not None else "low",
            "evidence_count": round(total_evidence, 4)
        }

    return scores


def aggregate_review_scores(review_scores_list: list) -> Dict:
    """
    Aggregate individual review scores to company-level profile.
    """
    if not review_scores_list or len(review_scores_list) == 0:
        return None

    import statistics

    aggregated = {
        "hofstede": {},
        "mit_big_9": {},
        "schroders": {},
        "review_count": len(review_scores_list)
    }

    hofstede_dimensions = [
        "process_results", "job_employee", "professional_parochial",
        "open_closed", "tight_loose", "pragmatic_normative"
    ]

    for dimension in hofstede_dimensions:
        scores = [
            r["hofstede"][dimension]["score"]
            for r in review_scores_list
            if r and r.get("hofstede", {}).get(dimension, {}).get("score") is not None
        ]
        evidence_counts = [
            r["hofstede"][dimension].get("evidence_count", 0)
            for r in review_scores_list
            if r and r.get("hofstede", {}).get(dimension, {}).get("score") is not None
        ]
        if scores:
            aggregated["hofstede"][dimension] = {
                "mean": statistics.mean(scores),
                "std": statistics.stdev(scores) if len(scores) > 1 else 0,
                "count": len(scores),
                "total_evidence": sum(evidence_counts)
            }

    mit_dimensions = [
        "agility", "collaboration", "customer_orientation", "diversity",
        "execution", "innovation", "integrity", "performance", "respect"
    ]

    for dimension in mit_dimensions:
        scores = [
            r["mit_big_9"][dimension]["score"]
            for r in review_scores_list
            if r and r.get("mit_big_9", {}).get(dimension, {}).get("score") is not None
        ]
        evidence_counts = [
            r["mit_big_9"][dimension].get("evidence_count", 0)
            for r in review_scores_list
            if r and r.get("mit_big_9", {}).get(dimension, {}).get("score") is not None
        ]
        if scores:
            aggregated["mit_big_9"][dimension] = {
                "mean": statistics.mean(scores),
                "std": statistics.stdev(scores) if len(scores) > 1 else 0,
                "count": len(scores),
                "total_evidence": sum(evidence_counts)
            }

    for dimension in SCHRODERS_DIMENSIONS:
        scores = [
            r["schroders"][dimension]["score"]
            for r in review_scores_list
            if r and r.get("schroders", {}).get(dimension, {}).get("score") is not None
        ]
        evidence_counts = [
            r["schroders"][dimension].get("evidence_count", 0)
            for r in review_scores_list
            if r and r.get("schroders", {}).get(dimension, {}).get("score") is not None
        ]
        if scores:
            aggregated["schroders"][dimension] = {
                "mean": statistics.mean(scores),
                "std": statistics.stdev(scores) if len(scores) > 1 else 0,
                "count": len(scores),
                "total_evidence": sum(evidence_counts)
            }

    return aggregated


